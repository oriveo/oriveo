#!/usr/bin/env node
// Generates the Web rejection-signature table from shared/test-fixtures/capability/rejection-signatures.v1.json (only byWireFamily / byProtocol).
// Usage: node scripts/generate-rejection-signatures.mjs (from apps/app); the drift test calls generateRejectionSignaturesSource() directly.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const FIXTURE_RELATIVE = "test-fixtures/capability/rejection-signatures.v1.json";

/** Walk up from the script directory to the fixture under `shared/`; report the starting point when it is missing. */
function findFixturePath(start) {
  let dir = start;
  for (;;) {
    for (const sharedDir of ["shared"]) {
      const candidate = resolve(dir, sharedDir, FIXTURE_RELATIVE);
      if (existsSync(candidate)) return candidate;
    }
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`rejection signatures fixture not found above ${start}`);
    dir = parent;
  }
}

export const FIXTURE_PATH = findFixturePath(here);
export const OUTPUT_PATH = resolve(here, "../lib/core/capability/rejection-signatures.generated.ts");

/** Keep only the fields matching needs; candidates / notFound stay out of the generated file. */
function pickSignature(entry) {
  const out = { signatureId: entry.signatureId, httpStatus: entry.httpStatus };
  if (entry.errorCode !== undefined) out.errorCode = entry.errorCode;
  out.messagePattern = entry.messagePattern;
  out.kind = entry.kind;
  if (entry.capabilityKey !== undefined) out.capabilityKey = entry.capabilityKey;
  if (entry.parameter !== undefined) out.parameter = entry.parameter;
  return out;
}

function pickGroups(groups) {
  return Object.fromEntries(
    Object.entries(groups ?? {}).map(([key, entries]) => [key, entries.map(pickSignature)]),
  );
}

export function generateRejectionSignaturesSource() {
  const fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8"));
  const lines = [
    "// GENERATED by scripts/generate-rejection-signatures.mjs from shared/test-fixtures/capability/rejection-signatures.v1.json. Do not edit.",
    "/* eslint-disable */",
    "",
    "export interface RejectionSignatureEntry {",
    "  readonly signatureId: string;",
    "  readonly httpStatus: number;",
    "  readonly errorCode?: string;",
    "  readonly messagePattern: string;",
    "  readonly kind: 'input_rejected' | 'param_rejected';",
    "  readonly capabilityKey?: string;",
    "  readonly parameter?: string;",
    "}",
    "",
    `export const REJECTION_SIGNATURES_VERSION = ${JSON.stringify(fixture.version)};`,
    "",
    `export const REJECTION_SIGNATURES_BY_WIRE_FAMILY: Readonly<Record<string, readonly RejectionSignatureEntry[]>> = ${JSON.stringify(pickGroups(fixture.byWireFamily), null, 2)};`,
    "",
    `export const REJECTION_SIGNATURES_BY_PROTOCOL: Readonly<Record<string, readonly RejectionSignatureEntry[]>> = ${JSON.stringify(pickGroups(fixture.byProtocol), null, 2)};`,
    "",
  ];
  return lines.join("\n");
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  writeFileSync(OUTPUT_PATH, generateRejectionSignaturesSource());
  console.log(`wrote ${OUTPUT_PATH}`);
}
