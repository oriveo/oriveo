#!/usr/bin/env node
// Generates the standalone Web validators (ajv standalone ESM) from shared/model-contracts/metadata_payload.v2.schema.json.
// Usage: node scripts/generate-metadata-validators.mjs (run inside apps/app); the drift test calls generateMetadataValidatorsSource() directly.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import Ajv2020, { _ } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import addFormats from "ajv-formats";

const here = dirname(fileURLToPath(import.meta.url));
const SCHEMA_RELATIVE = "model-contracts/metadata_payload.v2.schema.json";

/** Walk up from the script directory to find the schema under `shared/`; throws with the search start when missing. */
function findSchemaPath(start) {
  let dir = start;
  for (;;) {
    for (const sharedDir of ["shared"]) {
      const candidate = resolve(dir, sharedDir, SCHEMA_RELATIVE);
      if (existsSync(candidate)) return candidate;
    }
    const parent = dirname(dir);
    if (parent === dir) throw new Error(`metadata payload schema not found above ${start}`);
    dir = parent;
  }
}

export const SCHEMA_PATH = findSchemaPath(here);
export const OUTPUT_PATH = resolve(here, "../lib/core/metadata/metadata-payload-validators.generated.js");

/** Export name -> $defs pointer inside the schema. */
const EXPORTS = {
  fullOrIndex: "#/$defs/fullOrIndex",
  catalog: "#/$defs/catalog",
  provider: "#/$defs/provider",
  model: "#/$defs/model",
};

// The output only depends on the date-time check from ajv-formats (named ESM import); unicode:false makes minLength use .length and drops the ajv runtime require.
const HEADER = [
  "// GENERATED by scripts/generate-metadata-validators.mjs from shared/model-contracts/metadata_payload.v2.schema.json. Do not edit.",
  "/* eslint-disable */",
  "// @ts-nocheck",
  'import { fullFormats as metadataPayloadFormats } from "ajv-formats/dist/formats.js";',
  "",
].join("\n");

function assertLengthLimitsSafeForUtf16(node, at = "#") {
  if (Array.isArray(node)) return node.forEach((item, index) => assertLengthLimitsSafeForUtf16(item, `${at}/${index}`));
  if (!node || typeof node !== "object") return;
  if ("maxLength" in node || ("minLength" in node && node.minLength > 1)) {
    throw new Error(`${at}: length limits other than minLength 1 differ between UTF-16 and code points; revisit unicode: false`);
  }
  for (const [key, value] of Object.entries(node)) assertLengthLimitsSafeForUtf16(value, `${at}/${key}`);
}

export function generateMetadataValidatorsSource() {
  const schema = JSON.parse(readFileSync(SCHEMA_PATH, "utf8"));
  assertLengthLimitsSafeForUtf16(schema);
  // unicode: false keeps ajv from emitting require("ajv/dist/runtime/ucs2length"), which the ESM
  // output cannot carry; lengths are then counted in UTF-16 units, safe only while every limit is minLength 1.
  const ajv = new Ajv2020({ allErrors: false, strict: false, unicode: false, logger: false,
    code: { source: true, esm: true, formats: _`metadataPayloadFormats` },
  });
  addFormats(ajv, ["date-time"]);
  ajv.addSchema(schema);
  const refs = Object.fromEntries(
    Object.entries(EXPORTS).map(([name, pointer]) => [name, `${schema.$id}${pointer}`]),
  );
  const source = standaloneCode(ajv, refs);
  if (source.includes("require(")) {
    throw new Error("generated metadata validators still contain require(); adjust generator options");
  }
  return HEADER + source + "\n";
}

const invokedDirectly = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  writeFileSync(OUTPUT_PATH, generateMetadataValidatorsSource());
  console.log(`wrote ${OUTPUT_PATH}`);
}
