import type { ChatMessage } from '@oriveo/shared';
import { ContextAssembler } from '@oriveo/core/context/assemble';
import { projectPlanMessages, type PlannedChatRequest } from './transport-input';

/** One message of a compaction summary request (produced by core summaryRequest). */
export interface CompactionPurposeMessage {
  role: 'user' | 'assistant';
  text: string;
}

export type PurposeRequestInput =
  | {
    purpose: 'crosscheck' | 'memoryExtraction';
    purposeSystem: string;
    userText: string;
  }
  | {
    /** Compaction summary: system is chosen by the caller (req.system ?? the system of this chat plan) and sent verbatim. */
    purpose: 'compaction';
    system: string | null;
    messages: readonly CompactionPurposeMessage[];
    /** Conversation instructions (the compaction assembly input carries instructions); defaults to ''. */
    instructions?: string;
  };

/**
 * Single-purpose request (crosscheck / memoryExtraction / compaction), produced by the assembler.
 * - crosscheck / memoryExtraction: purposeSystem + one user data message;
 * - compaction: the summary request's messages serve as the history unchanged, and system is the one the caller chose.
 * None carry memory or [D]; only compaction carries instructions; the window is unknown (no budget trimming).
 * Only returns a PlannedChatRequest; outbound messages (including role=system) are always generated by transportInput.
 */
export function assemblePurposeRequest(input: PurposeRequestInput): PlannedChatRequest {
  if (input.purpose === 'compaction') return assembleCompactionRequest(input);
  const source = {
    id: `${input.purpose}-source`,
    role: 'user',
    text: input.userText,
    state: 'delivered',
    attachments: [],
  } as const;
  const plan = ContextAssembler.assemble({
    purpose: input.purpose,
    window: { W: null, windowKind: 'total', maxOutput: {} },
    conversation: { id: input.purpose, useMemory: false },
    history: [{ ...source, attachments: [] }],
    purposeSystem: input.purposeSystem,
  });
  return projectPlanMessages(plan, [source as unknown as ChatMessage]);
}

function assembleCompactionRequest(input: Extract<PurposeRequestInput, { purpose: 'compaction' }>): PlannedChatRequest {
  const sources = input.messages.map((message, index) => ({
    id: `compaction-${index}`,
    role: message.role,
    text: message.text,
    state: 'delivered',
    attachments: [],
  } as const));
  const plan = ContextAssembler.assemble({
    purpose: 'compaction',
    window: { W: null, windowKind: 'total', maxOutput: {} },
    // useMemory=false: core's compaction purpose would inject memory, but the chat plan's system already contains memory, so no second copy is injected.
    conversation: { id: 'compaction', useMemory: false, instructions: input.instructions ?? '' },
    history: sources.map((source) => ({ ...source, attachments: [] })),
  });
  // Replaced with the system the caller chose (the chat plan's system already contains the instructions), verbatim.
  return projectPlanMessages({ ...plan, system: input.system }, sources as unknown as ChatMessage[]);
}
