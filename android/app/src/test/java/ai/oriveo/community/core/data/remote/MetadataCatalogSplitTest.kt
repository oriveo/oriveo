        // The index is fetched once more (twice in total) and the catalog tried once each; still mismatched -> keep last good and report.
        assertEquals(2, server.indexValidators.size)
        assertEquals(listOf("openAI", "openAI"), server.catalogCalls.map { it.first })
        assertEquals(lastGood, client.resolveCatalogModel(brokenOpenAIModel, ProviderKind.OpenAI)?.contentOnly())
        assertEquals(listOf("catalog_revision"), reports.map { it["phase"] })
    }

    @Test
    fun `404 catalog is never an empty catalog and pending is not a miss`() = runTest {
        val root = fixture()
        val notFound = (negativeCase(root, "unknownProvider").getValue("status") as JsonPrimitive).content.toInt()
        val server = FakeSplitServer(root)
        server.statusOverrides["anthropic"] = notFound
