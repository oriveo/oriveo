    @Test
    fun `unresolved ref rejects the whole catalog and keeps last good`() = runTest {
        val root = fixture()
        val server = FakeSplitServer(root)
        // First generation: the openAI catalog is valid under an older revision (last good).
        server.setCatalogRevision("openAI", "sha256:previous")
        server.setModelDisplayName("openAI", intactOpenAIModel, "Mini (previous)")
        val reports = mutableListOf<Map<String, String>>()
        val client = newClient(server, FakeRowDao(), demand(ProviderKind.OpenAI), reports = reports)
        client.initialize(context())
        val lastGood = client.resolveCatalogModel(brokenOpenAIModel, ProviderKind.OpenAI)?.contentOnly()
        assertNotNull(lastGood)

        // Second generation: the index points at a new revision, but one ref in the catalog is missing from its tables.
        server.resetCatalog("openAI", negativeCase(root, "unresolvedRef").getValue("catalog").jsonObject)
        client.refresh()

        // Content is still last good; only the publication revision on evidence follows the new index.
        assertEquals(lastGood, client.resolveCatalogModel(brokenOpenAIModel, ProviderKind.OpenAI)?.contentOnly())
        // Another model with intact refs in the same catalog is not adopted on its own either: rejection covers the whole catalog.
        assertEquals(
            "Mini (previous)",
            client.resolveCatalogModel(intactOpenAIModel, ProviderKind.OpenAI)?.displayName,
        )
        assertEquals(MetadataClient.CatalogLoadState.Loaded, client.catalogLoadState(ProviderKind.OpenAI))
        assertEquals(listOf("catalog_decode"), reports.map { it["phase"] })

        // Without a last good the catalog is rejected just the same: the provider stays pending instead of "empty catalog".
        val fresh = FakeSplitServer(root)
        fresh.resetCatalog("openAI", negativeCase(root, "unresolvedRef").getValue("catalog").jsonObject)
        val coldClient = newClient(fresh, FakeRowDao(), demand(ProviderKind.OpenAI), reports = mutableListOf())
        coldClient.initialize(context())
        assertNull(coldClient.resolveCatalogModel(brokenOpenAIModel, ProviderKind.OpenAI))
        assertEquals(MetadataClient.CatalogLoadState.Pending, coldClient.catalogLoadState(ProviderKind.OpenAI))
    }

    @Test
    fun `revision mismatch refetches index once then keeps last good`() = runTest {
        val root = fixture()
        val server = FakeSplitServer(root)
        val reports = mutableListOf<Map<String, String>>()
        val client = newClient(server, FakeRowDao(), demand(ProviderKind.OpenAI), reports = reports)
        client.initialize(context())
        val lastGood = client.resolveCatalogModel(brokenOpenAIModel, ProviderKind.OpenAI)?.contentOnly()
        assertNotNull(lastGood)

        val mismatch = negativeCase(root, "revisionMismatch")
        server.setIndexRevisionOnly(
            mismatch.getValue("provider").let { (it as JsonPrimitive).content },
            (mismatch.getValue("indexCatalogRevision") as JsonPrimitive).content,
        )
        server.indexValidators.clear()
        server.catalogCalls.clear()
