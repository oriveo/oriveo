    /** Server double: index and catalogs each carry an ETag; a matching If-None-Match returns 304. */
    private class FakeSplitServer(root: JsonObject) : MetadataSplitTransport {
        private var index: JsonObject = root.getValue("indexResponse").jsonObject
        private val catalogs: MutableMap<String, JsonObject> = root.getValue("catalogResponses").jsonObject
            .mapValues { (_, value) -> value.jsonObject.getValue("data").jsonObject }
            .toMutableMap()
        private var indexGeneration = 0
        val indexValidators = mutableListOf<String?>()
        val catalogCalls = mutableListOf<Pair<String, String?>>()
        val statusOverrides = mutableMapOf<String, Int>()
        var indexStatusOverride: Int? = null

        private fun indexETag() = if (indexGeneration == 0) INDEX_ETAG else "\"index-$indexGeneration\""
        private fun catalogETag(key: String) = "\"catalog-$key-${revisionOf(catalogs.getValue(key))}\""
        private fun revisionOf(data: JsonObject) = (data.getValue("catalogRevision") as JsonPrimitive).content

        override suspend fun fetchIndex(ifNoneMatch: String?, cacheBust: String?): MetadataTransportResponse {
            indexValidators += ifNoneMatch
            indexStatusOverride?.let { return MetadataTransportResponse(it, null, null, 0) }
            if (ifNoneMatch == indexETag()) return MetadataTransportResponse(304, indexETag(), null, 0)
            val body = index.toString()
            return MetadataTransportResponse(200, indexETag(), body, body.length.toLong())
        }

        override suspend fun fetchCatalog(provider: String, ifNoneMatch: String?, revision: String?): MetadataTransportResponse {
            catalogCalls += provider to ifNoneMatch
            statusOverrides[provider]?.let { return MetadataTransportResponse(it, null, null, 0) }
            val data = catalogs[provider] ?: return MetadataTransportResponse(404, null, null, 0)
            val eTag = catalogETag(provider)
            if (ifNoneMatch == eTag) return MetadataTransportResponse(304, eTag, null, 0)
            val body = JsonObject(mapOf("code" to JsonPrimitive(0), "data" to data, "message" to JsonPrimitive("ok"))).toString()
            return MetadataTransportResponse(200, eTag, body, body.length.toLong())
        }

        /** Changes the catalog and the revision the index lists for it together (one server snapshot change). */
        fun setCatalogRevision(key: String, revision: String) {
            catalogs[key] = JsonObject(catalogs.getValue(key) + ("catalogRevision" to JsonPrimitive(revision)))
            setIndexRevisionOnly(key, revision)
        }

        fun setModelDisplayName(key: String, modelId: String, displayName: String) {
            val data = catalogs.getValue(key)
            val models = data.getValue("models").jsonObject
            val model = models.getValue(modelId).jsonObject
            catalogs[key] = JsonObject(
                data + ("models" to JsonObject(models + (modelId to JsonObject(model + ("displayName" to JsonPrimitive(displayName)))))),
            )
        }

        fun resetCatalog(key: String, data: JsonObject) {
            catalogs[key] = data
            setIndexRevisionOnly(key, revisionOf(data))
        }

        fun setIndexRevisionOnly(key: String, revision: String) {
            editIndexData { data ->
                val providers = data.getValue("providers").jsonObject
                val provider = providers.getValue(key).jsonObject
                data + ("providers" to JsonObject(providers + (key to JsonObject(provider + ("catalogRevision" to JsonPrimitive(revision))))))
            }
        }

        fun bumpIndexETag() = editIndexData { it }

        fun setIndexMetadataRevision(revision: Long) {
            editIndexData { data -> data + ("metadataRevision" to JsonPrimitive(revision)) }
        }

        fun setWhitelist(keys: List<String>) {
            editIndexData { data ->
                data + ("relayRuntimeConfig" to JsonObject(mapOf("officialProviderWhitelist" to JsonArray(keys.map(::JsonPrimitive)))))
            }
        }

        private fun editIndexData(edit: (JsonObject) -> Map<String, JsonElement>) {
            val data = index.getValue("data").jsonObject
            index = JsonObject(index + ("data" to JsonObject(edit(data))))
            indexGeneration += 1
        }
    }

    /** Multi-row Room double with the production DAO's semantics (one row per key, substr chunks, touch updates only the timestamp). */
    private class FakeRowDao : MetadataCacheDao {
        val rows = linkedMapOf<String, MetadataCacheEntity>()
        var upsertCount = 0

        override suspend fun payloadLength(key: String): Int? =
            rows[key]?.payload?.let { it.codePointCount(0, it.length) }

        override suspend fun payloadChunk(start: Int, count: Int, key: String): String? {
            val payload = rows[key]?.payload ?: return null
            val total = payload.codePointCount(0, payload.length)
            val startIndex = (start - 1).coerceIn(0, total)
            val endIndex = (startIndex + count).coerceAtMost(total)
            return payload.substring(
                payload.offsetByCodePoints(0, startIndex),
                payload.offsetByCodePoints(0, endIndex),
            )
        }

        /** Writing these keys throws (simulates a disk write failure). */
        val failUpsertKeys = mutableSetOf<String>()

        override suspend fun upsert(entity: MetadataCacheEntity) {
            if (entity.key in failUpsertKeys) throw java.io.IOException("disk full")
            upsertCount += 1
            rows[entity.key] = entity
        }

        /** Same semantics as a Room transaction: any row failing rolls everything back. */
        override suspend fun upsertAllInTransaction(entities: List<MetadataCacheEntity>) {
            val before = LinkedHashMap(rows)
            try {
                entities.forEach { upsert(it) }
            } catch (error: Exception) {
                rows.clear()
                rows.putAll(before)
                throw error
            }
        }

        override suspend fun updatedAtMs(key: String): Long? = rows[key]?.updatedAtMs

        override suspend fun touch(key: String, updatedAtMs: Long): Int {
            val row = rows[key] ?: return 0
            rows[key] = row.copy(updatedAtMs = updatedAtMs)
            return 1
        }

        override suspend fun delete(key: String) {
            rows.remove(key)
        }

        override suspend fun deleteAllExcept(keep: String) {
            rows.keys.retainAll { it == keep }
        }

        override suspend fun clear() {
            rows.clear()
        }
    }

    private companion object {
        const val INDEX_ETAG = "\"index-0\""
        const val STALE_NOW = 10L * 24 * 60 * 60 * 1000
    }
