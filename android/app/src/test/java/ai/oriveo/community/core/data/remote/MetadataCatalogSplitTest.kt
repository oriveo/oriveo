        assertEquals(7, resolved.availableModelCount)
        // Provider-level fields come from the index and work before the catalog arrives.
        assertEquals(anthropicModel, client.defaultModelId(ProviderKind.Anthropic))
    }

    @Test
    fun `pending provider fetches only its own catalog and a loaded miss is a real miss`() = runTest {
        val server = FakeSplitServer(fixture())
        val client = newClient(server, FakeRowDao(), demand(ProviderKind.OpenAI))
        client.initialize(context())
        assertEquals(listOf("openAI"), server.catalogCalls.map { it.first })
        assertFalse(client.isSnapshotConfirmed(ProviderKind.Anthropic))

        val provider = Provider(
            id = "anthropic-1",
            kind = ProviderKind.Anthropic,
            models = listOf(AIModel(id = anthropicModel, name = anthropicModel)),
        )
        assertTrue(ProviderCatalogResolver.resolve(provider, client).catalogPending)
        // Reading pending repeatedly in one round does not spin: only one single-provider fetch is queued.
        assertEquals(MetadataClient.CatalogLoadState.Pending, client.catalogLoadState(ProviderKind.Anthropic))
        advanceUntilIdle()

        assertEquals(listOf("openAI", "anthropic"), server.catalogCalls.map { it.first })
        assertEquals(1, server.indexValidators.size)
        assertEquals(MetadataClient.CatalogLoadState.Loaded, client.catalogLoadState(ProviderKind.Anthropic))
        assertTrue(client.isSnapshotConfirmed(ProviderKind.Anthropic))
        val resolved = ProviderCatalogResolver.resolve(provider, client)
        assertFalse(resolved.catalogPending)
        assertEquals(corpusModelIds("anthropic").sorted(), resolved.catalog.filter { !it.isManual }.map { it.model.id }.sorted())
        // Catalog loaded and the model truly absent: a real miss.
        assertNull(client.resolveCatalogModel("claude-not-in-catalog", ProviderKind.Anthropic))
        assertEquals(MetadataClient.CatalogLoadState.Loaded, client.catalogLoadState(ProviderKind.Anthropic))
        assertEquals(2, server.catalogCalls.size)
    }

