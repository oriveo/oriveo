    @Test
    fun `split index plus catalogs decode identically to the lean equivalent`() = runTest {
        val server = FakeSplitServer(fixture())
        val client = newClient(server, FakeRowDao(), demand(ProviderKind.OpenAI, ProviderKind.Anthropic))

        client.initialize(context())

        // lean v1 deliberately does not project the fields listed in leanV1DroppedFields: the equivalence check uses a catalog with those keys removed,
        // and the production-path section below still uses the fixture as is (client).
        val equivalent = newClient(
            FakeSplitServer(withoutLeanV1DroppedFields(fixture())),
            FakeRowDao(),
            demand(ProviderKind.OpenAI, ProviderKind.Anthropic),
        )
        equivalent.initialize(context())

        val lean = MetadataClient()
        lean.loadNetworkPayloadForTesting(fixture().getValue("leanEquivalent").toString(), INDEX_ETAG)
        for (kind in listOf(ProviderKind.OpenAI, ProviderKind.Anthropic)) {
            val ids = lean.providerModelIds(kind)
            assertTrue(ids.isNotEmpty())
            assertEquals(ids, equivalent.providerModelIds(kind))
            assertEquals(lean.defaultModelId(kind), equivalent.defaultModelId(kind))
            assertEquals(lean.validation(kind), equivalent.validation(kind))
            assertEquals(lean.providerAttachmentSupport(kind), equivalent.providerAttachmentSupport(kind))
            for (id in ids) {
                // Model set, pricing, capabilities, generation parameter refs and evidence projection in one pass.
                assertEquals(lean.resolveCatalogModel(id, kind), equivalent.resolveCatalogModel(id, kind))
                assertEquals(
                    lean.capabilityActionLookup(kind, id, "generation"),
                    equivalent.capabilityActionLookup(kind, id, "generation"),
                )
                assertEquals(lean.capabilityActionLookup(kind, id, "web"), equivalent.capabilityActionLookup(kind, id, "web"))
            }
        }
        assertEquals(lean.relayRuntimeConfig(), equivalent.relayRuntimeConfig())
        assertEquals(lean.listPublicProviderConfigs(), equivalent.listPublicProviderConfigs())

        // The objects the production path produces must be right on their own too (expected values
        // come straight from the fixture tables): parametersRef dereferenced, evidence identity filled in from tree position, capabilityControls expanded.
        var checkedParameters = 0
        var checkedEvidence = 0
        var checkedControls = 0
        for ((key, kind) in listOf("openAI" to ProviderKind.OpenAI, "anthropic" to ProviderKind.Anthropic)) {
            val catalog = catalogData(key)
            val tables = catalog.getValue("tables").jsonObject
            for ((id, raw) in catalog.getValue("models").jsonObject) {
                val wire = raw.jsonObject
                val model = client.resolveCatalogModel(id, kind)!!
                val profile = (wire["profilesRef"] as? JsonPrimitive)?.content
                    ?.let { tables.getValue("profiles").jsonObject.getValue(it).jsonObject }
                val parametersRef = ((profile?.get("generation") as? JsonObject)?.get("parametersRef") as? JsonPrimitive)?.content
                if (parametersRef != null && model.profiles.generation != null) {
                    val expected = tables.getValue("generationParameters").jsonObject.getValue(parametersRef)
                        .let { it as JsonArray }.map { (it.jsonObject.getValue("id") as JsonPrimitive).content }
                    assertEquals(expected, model.profiles.generation?.parameters?.mapNotNull { it.id })
                    checkedParameters += 1
                }
                val evidence = (wire["capabilityEvidenceRef"] as? JsonPrimitive)?.content
                    ?.let { tables.getValue("capabilityEvidence").jsonObject.getValue(it).jsonObject }
                if (evidence != null) {
                    // After expanding capabilityEvidenceRef the namespace ownership must match the fixture;
                    // candidates that pass this client's source/grade allowlist get their identity from tree position.
                    val expectedKeys = (evidence.getValue("candidates") as JsonArray)
                        .map { (it.jsonObject.getValue("key") as JsonPrimitive).content }.toSet()
                    assertEquals(expectedKeys, model.capabilityEvidenceOwnedKeys)
                    assertEquals(false, model.capabilityEvidenceViewMalformed)
                    model.capabilityEvidenceCandidates.orEmpty().forEach { candidate ->
                        assertEquals(id, candidate.modelId)
                        assertEquals(INDEX_ETAG, candidate.metadataRevision)
                    }
                    checkedEvidence += 1
                }
                val controls = (wire["capabilityControlsRef"] as? JsonPrimitive)?.content
                    ?.let { tables.getValue("capabilityControls").jsonObject.getValue(it).jsonObject }
                controls?.forEach { (capability, control) ->
                    assertEquals(
                        (control.jsonObject["state"] as? JsonPrimitive)?.content,
                        client.capabilityActionLookup(kind, id, capability)?.state,
                    )
                    checkedControls += 1
                }
            }
        }
        // If the fixture ever lost these ref kinds, the loops above would run empty; they must really compare something.
        assertTrue(checkedParameters > 0)
        assertTrue(checkedEvidence > 0)
        assertTrue(checkedControls > 0)
        assertEquals(MetadataClient.CatalogLoadState.Loaded, client.catalogLoadState(ProviderKind.OpenAI))
        assertTrue(client.isSnapshotConfirmed(ProviderKind.OpenAI))
        assertEquals(MetadataClient.MetadataSource.FreshNetwork, client.metadataSource(ProviderKind.OpenAI))
    }

